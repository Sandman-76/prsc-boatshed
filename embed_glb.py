"""Embed models/*.glb into models.js as base64, so the page loads hulls on file:// (double-click).
Browsers block loading .glb files directly over file://, so the GLBs are inlined as data URIs.
Run from the boatshed-model folder after changing any .glb:  python embed_glb.py
"""
import base64, glob, os, json

d = os.path.dirname(os.path.abspath(__file__))
out = {}
for p in sorted(glob.glob(os.path.join(d, "models", "*.glb"))):
    key = "models/" + os.path.basename(p)      # must match the CLASS_GLB path strings in index.html
    with open(p, "rb") as f:
        out[key] = base64.b64encode(f.read()).decode("ascii")

with open(os.path.join(d, "models.js"), "w") as f:
    f.write("// Auto-generated by embed_glb.py: GLB hulls as base64 so they load on file:// (no server).\n")
    f.write("window.MODEL_B64=" + json.dumps(out) + ";\n")

print("embedded:", list(out.keys()))
print("models.js KB:", round(os.path.getsize(os.path.join(d, "models.js")) / 1024))
